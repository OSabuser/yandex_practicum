def get_input() -> tuple[int, int]:
    """Считывает количество ступеней и максимальную длину прыжка."""
    # Обрабатываем возможные лишние пробелы через split()
    n, k = map(int, input().split())
    return n, k


def solve_stairs(n: int, k: int) -> int:
    """Динамическое программирование со скользящим окном."""
    MOD = 10**9 + 7

    # Базовый случай: на первую ступеньку прыгать не надо, мы уже там
    if n == 1:
        return 1

    # Массив dp, где dp[i] - количество способов добраться до i-й ступеньки
    dp = [0] * (n + 1)
    dp[1] = 1

    # Сумма последних k элементов (изначально состоит только из dp[1])
    current_sum = 1

    # Начинаем прыгать со 2-й ступеньки
    for i in range(2, n + 1):
        # Количество способов для текущей ступеньки — это сумма окна
        dp[i] = current_sum

        # Расширяем окно вправо (добавляем текущую ступеньку)
        current_sum = (current_sum + dp[i]) % MOD

        # Сужаем окно слева (выбрасываем ступеньку, до которой уже не допрыгнуть)
        if i >= k + 1:
            # Прибавляем MOD перед взятием остатка, чтобы избежать
            # отрицательных чисел при вычитании в Python (на всякий случай)
            current_sum = (current_sum - dp[i - k] + MOD) % MOD

    return dp[n]


if __name__ == "__main__":
    n, k = get_input()
    print(solve_stairs(n, k))
