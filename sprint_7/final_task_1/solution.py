# Решил вычислять расстояние Левенштейна с помощью модификации алгоритма Вагнера — Фишера
# (Bottom-Up, широко используется Rust-программерами) - одним из методов двумерного динамического
# программирования.
#
# Задача нахождения расстояния разбивается на подзадачи: поиск минимального количества операций для
# превращения префикса первой строки длины i в префикс второй строки длины j.
#
# > Вычисление расстояния происходит в 4 этапа:
#
# 1. Подготовка и оптимизация памяти:
# - определяем длины строк. Чтобы минимизировать использование памяти, мы гарантируем,
# что строка t всегда является наименьшей (меняем s и t местами при необходимости).
# - вместо хранения матрицы (m+1) x (n+1), как сделано в базе Вагнером-Фишером, мы храним
# две строки: previous_dp (результаты для предыдущего префикса строки s) и current_dp
# (текущая вычисляемая строка).
#
# 2. Инициализация базовых случаев:
# - previous_dp инициализируется значениями от 0 до n. Это соответствует превращению пустой строки
# s (длина 0) в префиксы t длины j. Для этого требуется ровно j операций вставки.
#
# 3. Итеративное заполнение:
# - внешний цикл проходит по символам строки s (от 1 до m).
# - на каждом шаге создается current_dp, где current_dp[0] = i (превращение строки s длины i
# в пустую строку t требует i операций удаления).
# - внутренний цикл проходит по символам строки t (от 1 до n).
# - если символы совпадают (s[i-1] == t[j-1]): current_dp[j] = previous_dp[j-1]
# - если символы различаются, мы берем минимум из трёх возможных операций и прибавляем 1:
# current_dp[j] = 1 + min(previous_dp[j], current_dp[j-1], previous_dp[j-1])
# где:
# . previous_dp[j] - удаление символа из s
# . current_dp[j-1] - вставка символа в s
# . previous_dp[j-1] - замена символа
# - после завершения внутреннего цикла previous_dp обновляется ссылкой на current_dp.
# - ответ находится в previous_dp[n].
#
#
# 2. Доказательство корректности
#
# А. Оптимальная подструктура
# Если мы знаем минимальное расстояние между префиксами строк длин (i-1, j), (i, j-1) и (i-1, j-1),
# мы можем гарантированно найти минимальное расстояние для (i, j), так как любое атомарное
# изменение (вставка, удаление, замена) увеличивает общее расстояние ровно на 1.
#
# Б. Доказательство корректности переходов
# > Главный инвариант: ячейка dp табличного представления на шаге (i, j) всегда содержит
# минимальное количество операций редактирования для подстрок s[0..i-1] и t[0..j-1].
#
# - Базовые случаи корректны: превращение пустой строки в строку длины K всегда требует K
# вставок, а превращение строки длины K в пустую — K удалений.
# - Шаг индукции корректен: если символы равны - не нужно ничего менять, стоимость равна
# стоимости для префиксов без этих символов. Если они не равны, мы обязаны сделать одну
# операцию. Проверяются все 3 доступные по условию операции (вставка, удаление,
# замена) и жадно выбирается та, путь до которой был самым дешевым.
#
#
# 3. Временная сложность
# Сложность определяется двумя вложенными циклами, проходящими по длинам обеих строк.
#
# - Внешний цикл выполняется m раз (где m — длина строки s) - O(m).
# - Внутренний цикл выполняется n раз (где n — длина строки t) - O(n).
# - Внутри циклов: операции сравнения, сложения и нахождения минимума - O(1).
# - Подготовительный этап (swap строк и инициализация базового массива) - O(n).
#
# Суммарная временная сложность алгоритма: O(m * n)
#
#
# 4. Пространственная сложность
#
# Учитывая модификацию алгоритма Вагнера — Фишера с оптимизацией хранения матрицы:
# - Мы не храним матрицу m * n целиком.
# - В памяти одновременно находятся только два одномерных массива: previous_dp и current_dp.
# - Длина каждого из этих массивов равна n + 1 (длина более короткой строки + 1).
#
# Итоговая пространственная сложность: O(min(m, n)) [https://rustp.org/dynamic-programming/edit-distance/].
#


def levenshtein_distance(s, t):
    """
    Вычисление расстояния Левенштейна между строками s и t
    с модификацией Bottom-up
    """

    if len(s) < len(t):
        s, t = t, s

    m, n = len(s), len(t)

    # previous_dp хранит значения для предыдущей строки (i-1)
    previous_dp = list(range(n + 1))

    for i in range(1, m + 1):
        # current_dp - текущая строка таблицы
        current_dp = [0] * (n + 1)

        # Базовый случай: превращение строки длины i в пустую требует i удалений
        current_dp[0] = i

        for j in range(1, n + 1):
            if s[i - 1] == t[j - 1]:
                # Символы равны — ничего не делаем, берем результат по диагонали
                current_dp[j] = previous_dp[j - 1]
            else:
                # Символы разные — берем минимум из удаления, вставки и замены + 1
                current_dp[j] = 1 + min(
                    previous_dp[j],  # Удаление (из s)
                    current_dp[j - 1],  # Вставка (в s)
                    previous_dp[j - 1],  # Замена
                )

        # Текущая строка становится предыдущей для следующего шага
        previous_dp = current_dp

    return previous_dp[n]


def get_input_strings():
    s = input().strip()
    t = input().strip()
    return s, t


if __name__ == "__main__":
    s, t = get_input_strings()
    print(levenshtein_distance(s, t))
