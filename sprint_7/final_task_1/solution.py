def get_input() -> tuple[str, str]:
    """Считывает две строки из стандартного ввода."""
    s = input().strip()
    t = input().strip()
    return s, t


def levenshtein_distance(s: str, t: str) -> int:
    """
    Вычисляет расстояние Левенштейна между строками s и t
    с оптимизацией по памяти O(min(|s|, |t|)).
    """
    # Для максимальной экономии памяти делаем так, чтобы t была более короткой строкой.
    # Тогда размер нашего массива dp будет равен длине самой короткой строки.
    if len(s) < len(t):
        s, t = t, s

    m, n = len(s), len(t)

    # prev_dp хранит значения для предыдущей строки (i-1)
    # Базовый случай: превращение пустой строки в строку t длины j требует j вставок
    prev_dp = list(range(n + 1))

    for i in range(1, m + 1):
        # curr_dp - текущая строка таблицы
        curr_dp = [0] * (n + 1)

        # Базовый случай: превращение строки длины i в пустую требует i удалений
        curr_dp[0] = i

        for j in range(1, n + 1):
            if s[i - 1] == t[j - 1]:
                # Символы равны — ничего не делаем, берем результат по диагонали
                curr_dp[j] = prev_dp[j - 1]
            else:
                # Символы разные — берем минимум из удаления, вставки и замены + 1
                curr_dp[j] = 1 + min(
                    prev_dp[j],  # Удаление (из s)
                    curr_dp[j - 1],  # Вставка (в s)
                    prev_dp[j - 1],  # Замена
                )

        # Текущая строка становится предыдущей для следующего шага
        prev_dp = curr_dp

    return prev_dp[n]


if __name__ == "__main__":
    s, t = get_input()
    print(levenshtein_distance(s, t))
