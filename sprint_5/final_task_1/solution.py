# 1. Принцип работы пирамидальной сортировки
# > Алгоритм работы следующий:
# A. Выбираем опорный pivot-элемент из исходного массива.
#   Выбор у нас производится случайным образом, главное чтобы это был один из элементов массива.
#   (Выбор элемента также можно осуществлять множеством способов: например, взять средний
#   элемент массива, первый элемент, последний или же медиану первого, среднего и последнего
#   последнего элементов)
#   Решил так, потому что согласно теории из Спринта №3 для случайно выбранного элемента сложно
#    подобрать killer-последовательность, а вот, например, для медианы  3 элементов
#   это возможно.
#
# B. Далее происходит самый важный момент - in-place разделение элементов массива на группы:
#   - Группа элементов, не превосходящих опорного.
#   - Группа элементов, превосходящих опорного.
#   В качестве схемы разделения выбран метод Хоара (https://ru.wikipedia.org/wiki/Быстрая_сортировка)
#   Данная схема использует два индекса (left_ptr в начале массива, right_ptr — в конце), которые
#   приближаются друг к другу, пока не найдётся пара элементов, где один больше опорного
#   и расположен перед ним, а второй — меньше и расположен после.
#   Эти элементы меняются местами. Обмен происходит до тех пор, пока индексы не пересекутся,
#   т.е. когда выполнится условие left_ptr >= right_ptr. Новых подмассивов здесь не создается,
#   работаем in-place с тем массивом, для которого осуществляем разделение.
#
#   При проходе по элементам массива используем обычный оператор сравнения "<",
#   при этом реализуя для класса Trainee dunder-метод __lt__(self, other), который
#   реализует кастомную логику сравнения участников, придуманную Тимофеем.
#   В результате мы получаем индекс разделения исходного массива на подмассивы:
#   - элементы, с индексами <= индекса разделения, не идут после pivot элемента;
#   - элементы, с индексами > (индекса разделения + 1), не идут до pivot элемента.
#
#  C. У нас возникает рекурсивный случай: до тех пор пока сортируемые подмассивы не будут иметь
#   длину 1 (базовый случай), мы будем рекурсивно вызывать сортировку для двух подмассивов. После
#   завершения сортировки двух подмассивов исходный массив будет представлять собой объединение
#   двух отсортированных массивов, т.е. будет отсортирован.
#
#
# 2. Доказательство корректности
#
# A. Реализация dunder-метода __lt__ для класса Trainee задаёт строгий порядок для участников.
# для двух участников trainee_1, trainee_2:
# - либо trainee_1 идет раньше trainee_2
# - либо trainee_2 идет раньше trainee_1
# Эти два условия взаимоисключающие.
#
# Б. Смотрел здесь
# https://neerc.ifmo.ru/wiki/index.php?title=Быстрая_сортировка и
# https://www.geeksforgeeks.org/dsa/hoare-s-partition-algorithm/
# В процессе разделения с учетом "строгости" реализации __lt__  выполняется:
#   1 Все элементы с индексами < left_ptr не идут после pivot элемента,
#   для них input_array[left_ptr] < pivot_element - False
#   2 Все элементы с индексами > right_ptr не идут до pivot элемента,
#   для них pivot_element < input_array[right_ptr]  - False
#   3 элементы между left_ptr и right_ptr пока не просмотрены
#   В конечном счете, все оставшиеся элементы между left_ptr и right_ptr
#   будут свапнуты, если для них не выполняются условия 1/2. Учитывая строгость сравнения,
#   (cм. 2 условия в пункте A) после операции swap, элементы займут правильные места.
#
# В. Корректность рекурсии обеспечивается тем, что после осуществления разделения исходного массива
# мы получаем два подмассива длина которых будет меньше чем длина исходного и в конечном счете
# мы достигнем базового случая.
#
# 3. Временная сложность
# По существу, временная сложность алгоритма определяется количеством операций разделений входного
# массива на подмассивы. Здесь всё зависит от того, насколько мы удачно выбрали опорный элемент.
# Средняя сложность при выборе случайного pivot элемента равна O(n*logn), худшая O(n^2), если нам
# попал на вход уже отсортированный массив. O(n*logn) складывается из:
# - Разделения входного массива O(n): проход по всем элементам. пока не left_ptr >= right_ptr
# - Рекурсивных вызовов сортировок подмассивов - O(logn)
# Если входной массив отсортирован, то будем иметь O(n) рекурсивных вызовов, в итоге получим
# сложность в худшем случае O(n^2)
#
# 4. Пространственная сложность
# За счёт того, что мы не создаем новые массивы в процессе разделения массива относительно опорного
# элемента, мы сокращаем потребление памяти здесь до O(1) [расход на переменные
# left_ptr, right_ptr и pivot_trainee заранее известен].
# Остальное потребление памяти зависит от глубины рекурсии. Она определяется выбором pivot элемента
# и входными данными (например, входной массив уже отсортирован) - в среднем случае O(logn), когда
# опорный элемент делит входной массив на две равные половины, в худшем случае, если входной массив
# уже отсортирован O(logn) выродится в O(N).
#
class Participant:
    """
    Данные участника соревнования
    """

    def __init__(self, login, solved, penalty):
        self.login = login
        self.solved = solved
        self.penalty = penalty

    def __lt__(self, other):
        """
        Правило сравнения: при сравнении двух участников выше будет идти тот,
        у которого решено больше задач. При равенстве числа решённых задач первым идёт участник
        с меньшим штрафом. Если же и штрафы совпадают, то первым будет тот, у которого логин
        идёт раньше в алфавитном (лексикографическом) порядке.
        """
        if not isinstance(other, Participant):
            raise TypeError

        # Больше решено
        if self.solved != other.solved:
            return self.solved > other.solved
        # Меньше штраф
        if self.penalty != other.penalty:
            return self.penalty < other.penalty
        # Лексикографический порядок раньше (буквы у нас все в нижнем регистре)
        return self.login < other.login


class MyBinHeap:
    def __init__(self):
        self.heap = [-1]

    def push(self, value):
        """Добавление элемента в кучу с просеиванием вверх"""
        self.heap.append(value)
        # Учитываем фиктивный элемент
        index = len(self.heap) - 1
        MyBinHeap._sift_up(self.heap, index)

    def pop_max(self):
        """Извлечение корневого элемента из кучи с просеиванием вниз"""

        if len(self.heap) - 1 == 0:
            raise IndexError("Heap is empty")

        root_element = self.heap[1]

        # Новый корень дерева - последний элемент
        self.heap[1] = self.heap[-1]
        self.heap.pop()

        # Если в куче ещё остались элементы, восстанавливаем свойство кучи
        if len(self.heap) > 1:
            MyBinHeap._sift_down(self.heap, 1)

        return root_element

    @staticmethod
    def _sift_down(heap, idx):
        """
        Просеивание вниз в куче на максимум.

        Args:
            heap: массив, представляющий кучу (индексация с 1, heap[0] фиктивный)
            idx: индекс элемента, от которого начинается просеивание

        Returns:
            int: индекс, на котором элемент оказался после просеивания
        """
        n = len(heap) - 1  # Реальный размер кучи (без фиктивного элемента)

        while True:
            largest = idx  # Изначально считаем текущего участника лучшим
            left = 2 * idx  # Индекс левого ребёнка
            right = 2 * idx + 1  # Индекс правого ребёнка

            # Проверяем левого ребёнка
            if left <= n and heap[left] < heap[largest]:
                largest = left

            # Проверяем правого ребёнка
            if right <= n and heap[right] < heap[largest]:
                largest = right

            # Если текущий участник уже самый лучший среди себя и детей - выходим
            if largest == idx:
                break

            # Меняем местами с максимальным ребёнком
            heap[idx], heap[largest] = heap[largest], heap[idx]

            # Продолжаем просеивание с новой позиции
            idx = largest

        return idx

    @staticmethod
    def _sift_up(heap, idx):
        """
        Просеивание вверх в куче на максимум.

        Args:
            heap: массив, представляющий кучу (индексация с 1, heap[0] фиктивный)
            idx: индекс элемента, от которого начинается просеивание

        Returns:
            int: индекс, на котором элемент оказался после просеивания
        """

        # Поднимаемся вверх, пока не достигнем корня или не найдем правильное место
        while idx > 1:  # idx=1 это корень, выше подниматься некуда
            parent = idx // 2  # Индекс родителя

            # Если текущий участник не лучше родителя, свойство кучи выполнено
            if not (heap[idx] < heap[parent]):
                break

            # Меняем местами с родителем (текущий участник лучше)
            heap[idx], heap[parent] = heap[parent], heap[idx]

            # Продолжаем просеивание с позиции родителя
            idx = parent

        return idx


def get_participants_data():
    """
    Ввод данных участников
    """
    n = int(input())
    participants = []
    for _ in range(n):
        login, solved, penalty = input().split()
        participants.append(Participant(login, int(solved), int(penalty)))
    return participants


