# 1. Принцип работы пирамидальной сортировки
# > Алгоритм работы следующий:
# Сортировка выполняется с помощью свойств бинарной кучи-пирамиды, которая описывается
# классом MyBinHeap. Для такой структуры данных известно, что  корнем кучи является
# самый высокоприоритетный элемент, а приоритеты остальных ее вершин не меньше, чем
# значения её потомков (это справедливо для структуры max_heap, именно её я и
# реализовал и использовал для решения задачи).
# > Пирамидальная сортировка состоит из двух этапов (вдохновлялся https://habr.com/ru/articles/112222/):
#   1. Построение кучи (метод push) с последующим просеиванием вверх после добавления
#   очередного участника.
#   2. Извлечение из кучи n участников (метод pop_max), в порядке их приоритета
#   с последующим просеиванием вниз после извлечения очередного участника соревнований.
#
# > Выполнение операций просеивания (реализованы как статические методы sift_up, sift_down
# класса MyBinHeap) после выполнения операций добавления/извлечения участников в куче,
# обеспечивает поддержку свойств бинарной кучи. Извлекая каждый раз из кучи её корень-очередного
# участника, мы получаем упорядоченную "по правилу Тимофея" последовательность участников:
# самым первым будет извлечён участник с самым высоким приоритетом и далее - в порядке
# убывания приоритета.
#
# Для представления участников в куче используется класс Participant, в котором также реализован
# dunder-метод __lt__ (его мы используем для сравнения узлов между собой при просеивании; если
# Participant_1 < Participant_2, то Participant_1 идет раньше Participant_2
# => он имеет приоритет выше).
#
#
# 2. Доказательство корректности
#
# A. Корректность сравнения участников
# Реализация dunder-метода __lt__ для класса Participant задаёт строгий порядок для участников.
# для двух участников Participant_1, Participant_2:
# - либо Participant_1 идет раньше Participant_2
# - либо Participant_2 идет раньше Participant_1
# Эти два условия взаимоисключающие.
#
# Б. Доказательство корректности алгоритма
# > Главный инвариант бинарной кучи, на котором строится пирамидальная сортировка -
# ключ в любой вершине не меньше, чем значения её потомков.
# Это свойство гарантирует, что в корневой вершине находится самый приоритетный элемент.
# В нашем случае - корень — лучший участник во всём дереве; каждый ребёнок не лучше родителя.
#
# Поддержанием данного свойства на каждом шаге изменения кучи (вставка, удаление) можно доказать
# корректность алгоритма.
#
# - При добавлении нового участника в кучу инвариант поддерживается с помощью операции sift_up:
# 1. Участник всегда добавляется в конец кучи, что может нарушить инвариант.
# 2. Происходит последовательное сравнение добавленного участника с его родителем:
# . если добавленный участник не лучше своего родителя [not (child < parent)], то инвариант
# сохранён.
# . если добавленный участник лучше своего родителя [(child < parent)], то они
# меняются местами, после чего мы продолжаем сравнение участника с очередным родителем
# пока не найдем правильное место или пока не достигнем корня.
# . данный процесс просеивания конечен (всегда находим правильное место участника в куче).
#
# - При извелечении корня-участника из кучи инвариант поддерживается с помощью операции sift_down:
# 1. Участник всегда извлекается из корня кучи, после чего на его место становится
# её последний элемент - этот процесс может нарушить инвариант.
# 2. Происходит последовательный выбор лучшего участника между правым и левым потомками родителя:
# . если родитель не хуже, чем оба потомка, то инвариант сохранён.
# . если один из потомков лучше своего родителя, родитель поменяется с ним местами, после
# чего сравнение будет продолжено.
# . после каждого обмена местами мы спускаемся на слой ниже. Процесс конечный, так как высота дерева
# ограничена.
# . После окончания процесса просеивания вниз, корнем кучи будет являться лучший участник.
#
# Итого: Так как после каждого push и pop_max инвариант кучи сохраняется, корень всегда содержит
# лучшего из имеющихся участников. Пирамидальная сортировка выполняет n последовательных вызовов
# pop_max, каждый раз извлекая текущего лучшего участника.
#
#
# 3. Временная сложность
# > Сложность опеределяется операциями добавления/извлечения элемента в/из кучу/кучи.
#
# - Построение двоичной кучи
# n операций push:
# . O(1) добавление участника в конец массива
# . O(log⁡n) - просеивание участника вверх по дереву
# . Итого: O(nlog⁡n)
# - Вывод отсортированного списка участников
# n операций pop_max:
# . O(1) получение корня и перенос последнего элемента в корень
# . O(log⁡n) - просеивание участника вниз по дереву
# . Итого: O(nlog⁡n)
#
# Суммарная временная сложность: O(nlog⁡n)
#
# 4. Пространственная сложность
#
# Сама бинарная куча создается в рантайме единожды и представляет собой дерево на массиве с
# фиктивным элементом в начале.
# Каждый элемент кучи представляет собой участника с полями login, solved, penalty, занимающие
# O(1) памяти.
# Максимальное количество участников в куче равно n => объем требуемой памяти - O(n).
#
# Итоговая пространственная сложность: O(n)
#
class Participant:
    """
    Данные участника соревнования
    """

    def __init__(self, login, solved, penalty):
        self.login = login
        self.solved = solved
        self.penalty = penalty

    def __lt__(self, other):
        """
        Правило сравнения: при сравнении двух участников выше будет идти тот,
        у которого решено больше задач. При равенстве числа решённых задач первым идёт участник
        с меньшим штрафом. Если же и штрафы совпадают, то первым будет тот, у которого логин
        идёт раньше в алфавитном (лексикографическом) порядке.
        """
        if not isinstance(other, Participant):
            raise TypeError

        # Больше решено
        if self.solved != other.solved:
            return self.solved > other.solved
        # Меньше штраф
        if self.penalty != other.penalty:
            return self.penalty < other.penalty
        # Лексикографический порядок раньше (буквы у нас все в нижнем регистре)
        return self.login < other.login


class MyBinHeap:
    def __init__(self):
        self.heap = [-1]

    def push(self, value):
        """Добавление элемента в кучу с просеиванием вверх"""
        self.heap.append(value)
        # Учитываем фиктивный элемент
        index = len(self.heap) - 1
        MyBinHeap._sift_up(self.heap, index)

    def pop_max(self):
        """Извлечение корневого элемента из кучи с просеиванием вниз"""

        if len(self.heap) - 1 == 0:
            raise IndexError("Heap is empty")

        root_element = self.heap[1]

        # Новый корень дерева - последний элемент
        self.heap[1] = self.heap[-1]
        self.heap.pop()

        # Если в куче ещё остались элементы, восстанавливаем свойство кучи
        if len(self.heap) > 1:
            MyBinHeap._sift_down(self.heap, 1)

        return root_element

    @staticmethod
    def _sift_down(heap, idx):
        """
        Просеивание вниз в куче на максимум.

        Args:
            heap: массив, представляющий кучу (индексация с 1, heap[0] фиктивный)
            idx: индекс элемента, от которого начинается просеивание

        Returns:
            int: индекс, на котором элемент оказался после просеивания
        """
        n = len(heap) - 1  # Реальный размер кучи (без фиктивного элемента)

        while True:
            largest = idx  # Изначально считаем текущего участника лучшим
            left = 2 * idx  # Индекс левого ребёнка
            right = 2 * idx + 1  # Индекс правого ребёнка

            # Проверяем левого ребёнка
            if left <= n and heap[left] < heap[largest]:
                largest = left

            # Проверяем правого ребёнка
            if right <= n and heap[right] < heap[largest]:
                largest = right

            # Если текущий участник уже самый лучший среди себя и детей - выходим
            if largest == idx:
                break

            # Меняем местами с максимальным ребёнком
            heap[idx], heap[largest] = heap[largest], heap[idx]

            # Продолжаем просеивание с новой позиции
            idx = largest

        return idx

    @staticmethod
    def _sift_up(heap, idx):
        """
        Просеивание вверх в куче на максимум.

        Args:
            heap: массив, представляющий кучу (индексация с 1, heap[0] фиктивный)
            idx: индекс элемента, от которого начинается просеивание

        Returns:
            int: индекс, на котором элемент оказался после просеивания
        """

        # Поднимаемся вверх, пока не достигнем корня или не найдем правильное место
        while idx > 1:  # idx=1 это корень, выше подниматься некуда
            parent = idx // 2  # Индекс родителя

            # Если текущий участник не лучше родителя, свойство кучи выполнено
            if not (heap[idx] < heap[parent]):
                break

            # Меняем местами с родителем (текущий участник лучше)
            heap[idx], heap[parent] = heap[parent], heap[idx]

            # Продолжаем просеивание с позиции родителя
            idx = parent

        return idx


def get_participants_data():
    """
    Ввод данных участников
    """
    n = int(input())
    participants = []
    for _ in range(n):
        login, solved, penalty = input().split()
        participants.append(Participant(login, int(solved), int(penalty)))
    return participants


