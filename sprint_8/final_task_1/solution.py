# 5. https://realpython.com/introduction-to-python-generators/
#
# Задача состоит из трёх этапов: парсинг в AST, ленивая распаковка через генераторы
# и поиск наибольшего общего префикса.
#
# > Вычисление происходит следующим образом:
#
# 1. Парсинг в абстрактное синтаксическое дерево (AST):
# - Вместо прямой распаковки используем стек для перевода запакованной строки в структуру
#   данных: список из символов и кортежей (множитель, вложенный список).
# - Это занимает минимум памяти, пропорционально только длине сжатой строки (S_i).
#
# 2. Ленивая распаковка (Generators):
# - Функция decompress_gen принимает AST и через `yield` и `yield from` посимвольно
#   возвращает распакованную строку, не склеивая её в памяти.
#
# 3. Поиск префикса:
# - Парсим первую строку в AST-эталон и задаем начальную длину LCP (lcp_length = inf).
# - Читаем остальные строки, превращаем их в AST.
# - Одновременно запускаем два генератора (от эталона и от текущей строки).
# - Синхронно сравниваем их символы (с помощью zip) и обновляем lcp_length.
# - В самом конце, зная финальную длину префикса, генерируем итоговую строку из эталона.
# 2. Доказательство корректности
#
# Определяется корректностью алгоритма распаковки и поиска наибольшего общего префикса
#
# А. Корректность распаковки
# - Стек обеспечивает правильную обработку вложенности и формирование дерева AST.
# - Генератор рекурсивно обходит узлы, что в точности соответствует математическому
#   правилу раскрытия скобок n[A].
#
# Б. Корректность поиска наибольшего общего префикса
# - Общий префикс обладает свойством ассоциативности:
#   lcp(s1, s2, s3) = lcp(lcp(s1, s2), s3).
# - Следовательно, последовательное попарное вычисление префикса для всех строк гарантированно
#   даст верный глобальный префикс для всего массива.
#
# 3. Временная сложность
# (https://algo.monster/liteproblems/394, https://algo.monster/liteproblems/14)
# Сложность алгоритма складывается из пошагового выполнения операций для каждой строки:
#
# - Обработка базовой строки:
# . Построение AST-дерева занимает O(S_1), где S_1 — длина запакованной строки.
#
# - Основной цикл (обработка оставшихся n - 1 строк):
# На каждой итерации i последовательно выполняются:
# . Считывание строки из потока ввода и парсинг в AST: O(S_i).
# . Сравнение префиксов (через генераторы): в худшем случае сравнивает все символы
#   текущей строки. Для худшего случая сложность: O(L_max),
#   где L_max — максимальная длина распакованной строки (<= 10^5).
# . Итого на одну итерацию цикла в худшем случае: O(L_max).
#
# Итоговая временная сложность для всех n запакованных строк:
# Точную сумму длин всех распакованных строк мы не знаем, но знаем, что у нас n строк,
# каждая из которых после распаковки не больше чем L_max.
# Получается что, суммарная сложность ограничена: O(n * L_max) = 1000 * 10^5 = 10^8 операций.
#
#
# . Итого на одну итерацию цикла: O(S_i) + O(L_i) + O(L_i) = O(L_i), так как S_i <= L_i.
#
# Итоговая временная сложность для всех n запакованных строк:
# O(L_1) + O(L_2) + ... + O(L_n) = O(SUM(L_i)).
#
# 4. Пространственная сложность
#
# - AST-дерево эталонной строки занимает память, пропорциональную длине её сжатого
#   представления: O(S_1).
# - В цикле временно хранится AST текущей проверяемой строки: O(S_i).
# - Единственная распакованная строка, которая собирается целиком — это финальный
#   результат, требующий памяти O(lcp_length) <= O(L_max).
#
# Итоговая пространственная сложность: O(S_max + L_max) в моменте финальной сборки ответа.
# В процессе самого поиска и сравнения строк память ограничена O(S_max)
#


def parse_to_ast(packed_str: str) -> list:
    """
    Парсит запакованную строку в абстрактное синтаксическое дерево (AST).
    """
    stack = []
    current_ast = []
    current_num = 0

    for char in packed_str:
        if char.isdigit():
            current_num = current_num * 10 + int(char)
        elif char == "[":
            # Сохраняем текущий контекст в стек и начинаем собирать внутренний
            stack.append((current_ast, current_num))
            current_ast = []
            current_num = 0
        elif char == "]":
            # Достаем контекст на уровень выше
            prev_ast, num = stack.pop()
            # Добавляем в него то, что собрали внутри скобок, как единый узел AST
            prev_ast.append((num, current_ast))
            # Возвращаемся к сборке внешнего контекста
            current_ast = prev_ast
        else:
            # Обычные буквы просто добавляем в текущий уровень AST
            current_ast.append(char)

    return current_ast


def decompress_gen(ast: list):
    """
    Ленивый генератор, который посимвольно обходит AST-дерево.
    """
    for node in ast:
        if isinstance(node, tuple):
            num, inner = node
            for _ in range(num):
                yield from decompress_gen(inner)
        else:
            yield node


def get_common_prefix_len(gen1, gen2, max_len: int) -> int:
    """
    Сравнивает два потока символов (генераторы) и возвращает длину их совпадения.
    Останавливается досрочно, если достигнут текущий максимум совпадения.
    """
    match_len = 0
    for c1, c2 in zip(gen1, gen2, strict=False):
        if match_len == max_len:
            break

        if c1 == c2:
            match_len += 1
        else:
            break

    return match_len


def main():
    n = int(input().strip())

    if n == 0:
        print("")
        return

    # Читаем первую строку и строим её AST (базовый эталон)
    first_packed = input().strip()
    base_ast = parse_to_ast(first_packed)

    # Храним только длину совпадения, а не саму строку, чтобы экономить память
    lcp_length = float("inf")

    # Сравниваем со всеми остальными строками
    for _ in range(n - 1):
        next_packed = input().strip()

        # Распаковываем и ищем общий префикс только если длина lcp еще > 0
        if lcp_length > 0:
            next_ast = parse_to_ast(next_packed)

            gen1 = decompress_gen(base_ast)
            gen2 = decompress_gen(next_ast)

            current_match = get_common_prefix_len(gen1, gen2, lcp_length)
            lcp_length = min(lcp_length, current_match)

    # Собираем итоговую строку-префикс
    result = []

    # Если n == 1, префикс — это вся распакованная первая строка
    if lcp_length == float("inf"):
        result = list(decompress_gen(base_ast))
    elif lcp_length > 0:
        for c in decompress_gen(base_ast):
            if len(result) == lcp_length:
                break
            result.append(c)

    print("".join(result))


if __name__ == "__main__":
    main()
