# ССЫЛКА НА ОТЧЁТ:
#
# 1. Принцип работы алгоритма
#
# Вдохновлялся:
# 1. https://medium.com/@iamhappycoder/leetcode-394-decode-string-6c78670ef7af
# 2. https://algo.monster/liteproblems/394
# 3. https://algo.monster/liteproblems/14
#
# Задача состоит из двух этапов: распаковка строк и поиск наибольшего
# общего префикса
#
# > Вычисление происходит следующим образом:
#
# 1. Распаковка :
# - Для распаковки строки со вложенными скобками используем стек (нечто похожее мы проворачивали в
# одном из спринтов раннее).
# - Проходим по каждому символу запакованной строки.
# - Если видим число, запоминаем его как множитель
# - Если видим открывающую скобку '[', кладем в стек текущий собранный фрагмент строки
#   и текущий множитель, после чего обнуляем их для сбора вложенной строки.
# - Если видим закрывающую скобку ']', достаем из стека предыдущий фрагмент и множитель.
#   Умножаем только что собранную внутри скобок строку на множитель и приклеиваем
#   к предыдущему фрагменту.
# - Обычные буквы добавляем к текущему фрагменту.
#
# 2. Поиск префикса:
# - Распаковываем первую строку и принимаем её за эталонный наибольший общий префикс.
# - Далее читаем остальные строки по одной, распаковываем текущую и сразу ищем её общий
#   префикс с сохраненным ранее эталонным префиксом.
# - Обновляем эталонный префикс. Если он стал пустым (current_lcp == "") пропускаем этап распаковки
# и поиска наибольшего общего префикса (ибо смысла нет искать дальше)
#
# 2. Доказательство корректности
#
# Определяется корректностью алгоритма распаковки и поиска наибольшего общего префикса
#
# А. Корректность распаковки
# - Стек обеспечивает правильную обработку вложенности. Самые глубокие скобки будут обработаны
# первыми при встрече первой закрывающей скобки ']':  это соответствует математическому
# правилу раскрытия скобок.
#
# Б. Корректность поиска наибольшего общего префикса
# - Общий префикс обладает свойством ассоциативности:
#   lcp(s1, s2, s3) = lcp(lcp(s1, s2), s3).
# - Следовательно, последовательное попарное вычисление префикса для всех строк гарантированно
#   даст верный глобальный префикс для всего массива.
#
# 3. Временная сложность
# (https://algo.monster/liteproblems/394, https://algo.monster/liteproblems/14)
# Сложность алгоритма складывается из пошагового выполнения операций для каждой строки:
#
# - Обработка первой (базовой) строки:
# . Функция decompress проходит по запакованной строке и формирует распакованную
# . Базовые операции со стеком -  O(1)
# . Итоговая склейка подстрок (умножение и конкатенация) пропорциональна длине
#   получившейся распакованной строки - L_1
# . Сложность первого шага: O(L_1)
#
# - Основной цикл (обработка оставшихся n - 1 строк):
# На каждой итерации i (от 2 до n) последовательно выполняются:
# . Считывание строки из потока ввода: O(S_i) [S_i — длина запакованной строки]
# . decompress занимает время, пропорциональное длине распакованной
#   строки L_i - O(L_i).
# . Сравнение префиксов (get_common_prefix): в худшем случае сравнивает все символы
#   текущей строки, если она полностью совпадает с эталонным префиксом.
#   Сложность: O(min(len(lcp), L_i)) = O(L_i).
#
# . Итого на одну итерацию цикла: O(S_i) + O(L_i) + O(L_i) = O(L_i), так как S_i <= L_i.
#
# Итоговая временная сложность для всех n запакованных строк:
# O(L_1) + O(L_2) + ... + O(L_n) = O(SUM(L_i)).
#
# 4. Пространственная сложность
#
# Благодаря попарному сравнению в памяти одновременно хранятся только:
# - текущий найденный наибольший общий префикс (длина <= 10^5)
# - стек для распаковки текущей строки и сама распакованная строка (длина <= 10^5)
#
# Итоговая пространственная сложность: O(max_L), где max_L <= 10^5.
#


def decompress(packed_str: str) -> str:
    """
    Распаковывает строку согласно рекурсивному правилу n[A].
    """
    stack = []
    current_str = []
    current_num = 0

    for char in packed_str:
        if char.isdigit():
            current_num = int(char)
        elif char == "[":
            # Кладем текущий контекст в стек и начинаем новый
            stack.append((current_str, current_num))
            current_str = []
            current_num = 0
        elif char == "]":
            # Достаем предыдущий контекст
            prev_str, num = stack.pop()
            # Расширяем его текущей собранной строкой, повторенной num раз
            prev_str.extend(current_str * num)
            current_str = prev_str
        else:
            # Обычный символ
            current_str.append(char)

    return "".join(current_str)


def get_common_prefix(s1: str, s2: str) -> str:
    """
    Поиск наибольшего общего префикса двух строк.
    """
    match_len = 0
    for c1, c2 in zip(s1, s2, strict=True):
        if c1 == c2:
            match_len += 1
        else:
            break
    return s1[:match_len]


def show_lcp_of_unpacked_strings():
    n = int(input().strip())

    # Читаем первую строку и берем ее как базовый префикс
    first_packed = input().strip()
    current_lcp = decompress(first_packed)

    # Сравниваем со всеми остальными строками
    for _ in range(n - 1):
        next_packed = input().strip()

        # Распаковываем и ищем общий префикс только если current_lcp не пустой
        if current_lcp:
            decompressed_next = decompress(next_packed)
            current_lcp = get_common_prefix(current_lcp, decompressed_next)

    print(current_lcp)


if __name__ == "__main__":
    show_lcp_of_unpacked_strings()


