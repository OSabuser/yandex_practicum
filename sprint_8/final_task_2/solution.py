# ССЫЛКА НА ОТЧЁТ: https://contest.yandex.ru/contest/26133/run-report/163442707/ы
#
# 1. Принцип работы алгоритма
#
# Вдохновлялся:
# 1. https://algo.monster/liteproblems/139
# 2. https://www.geeksforgeeks.org/word-break-problem-dp-32/
#
# Задача сводится к поиску пути разбиения строки на валидные слова.
#
# > Вычисление происходит в 3 основных этапа:
#
# 1. Подготовка структур данных:
# - Переводим словарь допустимых слов в множество для проверки вхождения за O(1).
# - Собираем длины всех слов из словаря. Оставляем только уникальные длины и сортируем их.
#   Ибо нет смысла отступать назад на 7 символов, если в словаре
#   нет ни одного слова длиной 7.
#
# 2. Определение базовых случаев и подготовка памяти (задача динамического программирования):
# - Создаем одномерный массив dp размером len(T) + 1, заполненный False
# - Каждый dp[i] означает: "можно ли разбить префикс текста T длиной i на слова из словаря"
# - Базовый случай: dp[0] = True (пустую строку всегда можно собрать)
#
# 3. Итеративное заполнение:
# - Внешний цикл проходит по всем символам текста от 1 до len(T)
# - Внутренний цикл проходит только по уникальным длинам слов из словаря
# - Формула перехода: если мы отступим от текущей позиции i на длину L назад (i - L),
#   и там разбиение было успешным (dp[i - L] == True), мы проверяем, есть ли
#   подстрока T[i - L : i] в множестве слов words_set.
# - Если да - dp[i] = True. Дальше проверять другие длины для текущего i не требуется и
#   мы осуществляем ранний выход из цикла.
#
# 2. Доказательство корректности
#
# А. Перекрытие подзадач
# - Если мы знаем, что префикс длины k успешно разбивается на слова, то валидность
#   префикса длины i (где i > k) зависит только от того, является ли остаток
#   строки (от k до i) словом из словаря.
#
# Б. Доказательство инварианта динамического программирования
# - База: dp[0] = True соответствует пустому разбиению.
# - Шаг: к концу обработки индекса i, значение dp[i] истинно тогда и только тогда,
#   когда найден такой индекс k < i, что префикс до k валиден (dp[k] == True) и суффикс
#   от k до i есть в словаре. Обращение только к валидным длинам L (где k = i - L)
#   гарантирует, что мы не пропустим ни одного возможного разбиения.
#
# 3. Временная сложность
#
# Сложность складывается из следующих шагов:
# - Создание множества слов: O(N * max_L), где N — количество слов, max_L — максисмальная длина слов
# - Внешний цикл проходит по длине текста: len(T) шагов
# - Внутренний цикл делает максимум U шагов, где U — количество уникальных длин слов
#   в словаре
# - Взятие среза T[i - L : i] и его проверка на вхождение в words_set занимает время O(L).
# - Срез и хеширование выполняются только если предыдущий префикс валиден
#
# Итоговая временная сложность: O(len(T) * U * max_L).
#
# 4. Пространственная сложность
#
# - Массив dp занимает O(len(T)) памяти.
# - Хранение словаря words_set занимает O(N * max_L).
#
# Итоговая пространственная сложность: O(|T| + N * max_L)
#


def can_break_string(text: str, words: list) -> str:

    words_set = set(words)

    # Храним только существующие длины слов, отсортированные по возрастанию
    word_lengths = sorted(list(set(len(w) for w in words)))

    n = len(text)
    dp = [False] * (n + 1)
    dp[0] = True  # Базовый случай

    for i in range(1, n + 1):
        for length in word_lengths:
            # Если длина слова больше текущего префикса,
            # проверять её и более длинные слова нет смысла
            if length > i:
                break

            if dp[i - length]:
                if text[i - length : i] in words_set:
                    dp[i] = True
                    break  # Нашли хотя бы одно разбиение для i, идем дальше

    return "YES" if dp[n] else "NO"


def get_input_data():
    text = input().strip()
    n = int(input().strip())

    words = []
    for _ in range(n):
        words.append(input().strip())

    return text, words


if __name__ == "__main__":
    text, words = get_input_data()
    print(can_break_string(text, words))
