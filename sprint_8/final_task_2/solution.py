# Задача сводится к поиску пути разбиения строки на валидные слова.
#
# > Вычисление происходит в 3 основных этапа:
#
# 1. Подготовка структур данных:
# - Построение префиксного дерева из допустимых слов.
# [
# Профиты Trie по сравнению с set:
# . Экономия памяти: слова с общими префиксами переиспользуют одни и те же узлы дерева.
# . Экономия времени: мы можем искать слова, просто спускаясь по узлам дерева
# посимвольно, без выделения памяти под новые подстроки
# ]
#
# 2. Определение базовых случаев и подготовка памяти (ДП):
# - Создаем одномерный массив dp размером len(T) + 1, заполненный False.
# - Каждый dp[i] означает: "можно ли разбить префикс текста T длиной i на слова".
# - Базовый случай: dp[0] = True (пустую строку всегда можно собрать).
#
# 3. Итеративное заполнение:
# - Внешний цикл проходит по индексам i от 0 до len(T) - 1:
# . Если dp[i] == False, префикс до i не собирается, пропускаем итерацию
# . Если dp[i] == True, мы делегируем поиск слов префиксному дереву, вызывая
#   метод trie.search(text, i).
# . Бор самостоятельно спускается по узлам и через генератор (yield) возвращает
#   индексы (end_index) всех найденных слов.
# . Получив валидный индекс от Бора, мы обновляем массив динамики: dp[end_index] = True.
#
#
# 2. Доказательство корректности
#
# А. Перекрытие подзадач
# - Если мы знаем, что префикс длины i успешно разбивается на слова, то валидность
#   любого более длинного префикса (до j+1) зависит только от того, образует ли
#   остаток строки (от i до j) валидное слово из словаря.
#
# Б. Доказательство инварианта динамического программирования
# - База: dp[0] = True соответствует пустому разбиению.
# - Шаг: двигаясь слева направо, мы гарантируем, что если dp[i] истинно, мы проложим
#   все возможные пути вперед до валидных j+1. Обращение только к реально существующим
#   в дереве символам отсекает невалидные ветви мгновенно, не пропуская ни одного
#   правильного разбиения.
#
# 3. Временная сложность
#
# Сложность складывается из следующих шагов:
# - Построение префиксного дерева: O(N * max_L), где N — количество слов,
#   max_L — максимальная длина слова.
# - Внешний цикл проходит по длине текста: len(T) шагов.
# - Внутренний цикл ограничен максимальной глубиной дерева, которая равна max_L
#   (в нашем случае <= 100 символов).
# - Переход по узлам дерева занимает O(1) за каждый символ.
# - Итого поиск подстрок занимает O(len(T) * max_L).
#
# Итоговая временная сложность: O(len(T) * max_L + N * max_L).
#
# 4. Пространственная сложность
#
# - Массив dp занимает O(len(T)) памяти.
# - Префиксное дерево в худшем случае занимает O(N * max_L), но на практике
#   значительно меньше из-за схлопывания общих префиксов.
#
# Итоговая пространственная сложность: O(len(T) + N * max_L).
#


class TrieNode:
    def __init__(self):
        self.children = {}
        self.is_end_of_word = False


class Trie:
    def __init__(self):
        self.root = TrieNode()

    def insert(self, word: str) -> None:
        """
        Вставляет слово в префиксное дерево.
        """
        node = self.root
        for char in word:
            if char not in node.children:
                node.children[char] = TrieNode()
            node = node.children[char]
        node.is_end_of_word = True

    def search(self, text: str, start_index: int):
        """
        Ищет слова в тексте, начиная со start_index.
        Возвращает (генерирует) индексы, на которых заканчиваются найденные слова.
        """
        node = self.root
        for j in range(start_index, len(text)):
            char = text[j]

            # Если символа нет в ветках дерева, значит таких слов больше нет
            if char not in node.children:
                break

            node = node.children[char]

            # Если дошли до конца какого-то слова, отдаем индекс его конца
            if node.is_end_of_word:
                yield j + 1


def can_break_string(text: str, words: list) -> bool:
    """
    Проверяет, можно ли разбить текст на слова из заданного списка.
    """
    trie = Trie()
    for word in words:
        trie.insert(word)

    n = len(text)
    dp = [False] * (n + 1)
    dp[0] = True  # Базовый случай

    for i in range(n):
        if not dp[i]:
            continue

        for end_index in trie.search(text, i):
            dp[end_index] = True

    return dp[n]


def get_input_data():
    text = input().strip()
    n = int(input().strip())

    words = []
    for _ in range(n):
        words.append(input().strip())

    return text, words


if __name__ == "__main__":
    text, words = get_input_data()

    if can_break_string(text, words):
        print("YES")
    else:
        print("NO")
